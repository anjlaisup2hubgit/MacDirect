-- Expand abbreviated campus codes (12WW) to the full street address.
-- Run once in the Supabase SQL editor. Safe to run again.

update public.societies set building = case building
  when '1CC' then '1 Central Courtyard'
  when '1IR' then '1 Innovation Road'
  when '1WW (Ainsworth Building)' then '1 Wally''s Walk (Ainsworth Building)'
  when '2FW' then '2 First Walk'
  when '2TP' then '2 Technology Place'
  when '2WW' then '2 Wally''s Walk'
  when '3IR' then '3 Innovation Road'
  when '3SR' then '3 Science Road'
  when '4ER' then '4 Eastern Road'
  when '4FW' then '4 First Walk'
  when '4RPD' then '4 Research Park Drive'
  when '4WW' then '4 Wally''s Walk'
  when '6ER' then '6 Eastern Road'
  when '6FW' then '6 First Walk'
  when '6SR' then '6 Science Road'
  when '6WW' then '6 Wally''s Walk'
  when '8HA (Incubator)' then '8 Hadenfeld Avenue (Macquarie University Incubator)'
  when '8LR (Banksia Cottage)' then '8 Link Road (Banksia Cottage)'
  when '8SCO' then '8 Sir Christopher Ondaatje Avenue'
  when '10GR (Macquarie University Sport and Aquatic Centre)' then '10 Gymnasium Road (Macquarie University Sport and Aquatic Centre)'
  when '10HA' then '10 Hadenfeld Avenue'
  when '10SCO' then '10 Sir Christopher Ondaatje Avenue'
  when '11WW' then '11 Wally''s Walk'
  when '12MW' then '12 Macquarie Walk'
  when '12SW' then '12 Second Way'
  when '12WW' then '12 Wally''s Walk (Mitchell Building)'
  when '13ARPD' then '13 Research Park Drive'
  when '13RPD' then '13 Research Park Drive'
  when '14ER' then '14 Eastern Road'
  when '14FW' then '14 First Walk (Macquarie University Special Education Centre)'
  when '14SCO' then '14 Sir Christopher Ondaatje Avenue'
  when '14SW' then '14 Second Way'
  when '15RPD' then '15 Research Park Drive'
  when '16MW (Waranara Library)' then '16 Macquarie Walk (Waranara Library)'
  when '16UA (Australian Hearing Hub)' then '16 University Avenue (Australian Hearing Hub)'
  when '16WW (Lincoln Building)' then '16 Wally''s Walk (Lincoln Building)'
  when '17MW' then '17 Macquarie Walk'
  when '17WW (Michael Kirby Building)' then '17 Wally''s Walk (Michael Kirby Law Building)'
  when '18ER' then '18 Eastern Road'
  when '18WW (Service Connect)' then '18 Wally''s Walk (Service Connect)'
  when '21WW (Macquarie Theatre)' then '21 Wally''s Walk (Macquarie Theatre)'
  when '23WW' then '23 Wally''s Walk (Price Theatre)'
  when '25WW' then '25 Wally''s Walk'
  when '27WW (Lotus Theatre)' then '27 Wally''s Walk (Lotus Theatre)'
  when '29WW' then '29 Wally''s Walk'
  when '75TR' then '75 Talavera Road'
  else building
end
where building ~ '^[0-9]+[A-Z]';

